export const LAKE_BOXES = raw.map(([a,b,c,d,e,f,mat,ramp]) => {
  const box = { min: [a,b,c], max: [d,e,f], mat };
  if (ramp) {
    const axis = ramp[1] === 'x' ? 0 : 2;
    box.ramp = { axis, dir: ramp[0] === '+' ? 1 : -1, slope: (e-b)/(axis === 0 ? d-a : f-c) };
  }
  return box;
});
